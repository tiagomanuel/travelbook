import assert from 'node:assert/strict';
import {readFileSync, existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
import {datesBetween,coordsValid,appleMaps,toCSV} from '../assets/utils.js';
import {validateBackup} from '../assets/db.js';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
for(const f of ['index.html','manifest.webmanifest','service-worker.js','assets/app.js','assets/style.css','assets/utils.js','assets/db.js','icons/icon-192.png','icons/icon-512.png','.nojekyll']) assert.ok(existsSync(join(root,f)),`Falta ${f}`);
assert.equal(datesBetween('2026-12-01','2026-12-03').length,3);
assert.equal(datesBetween('2026-12-03','2026-12-01').length,0);
assert.ok(coordsValid(41.9,12.5));
assert.ok(!coordsValid(91,12.5));
assert.ok(appleMaps({lat:41.9,lng:12.5},'transit').includes('dirflg=r'));
assert.ok(toCSV([{name:'=1+2'}],['name']).includes("'=1+2"));
assert.throws(()=>validateBackup({}),/incompatível/);
const manifest=JSON.parse(readFileSync(join(root,'manifest.webmanifest'),'utf8'));
assert.equal(manifest.start_url,'./');assert.equal(manifest.scope,'./');
assert.equal(manifest.display,'standalone');
console.log('Validações estáticas: OK');
